SELECT r.table_name,r.cols AS missing_unique_guard FROM (
SELECT 'tbpo_jasa_request' AS table_name,'kd_po_jasa' AS cols
UNION ALL SELECT 'tbpo_jasa_request','no_spk'
UNION ALL SELECT 'tbpo_jasa_scope','kd_po_jasa,revision_no,line_no'
UNION ALL SELECT 'tbpo_jasa_material','kd_po_jasa,revision_no,line_no'
UNION ALL SELECT 'tbpo_jasa_approval','action_token'
UNION ALL SELECT 'tbpo_jasa_spk','kd_po_jasa'
UNION ALL SELECT 'tbpo_jasa_spk','no_spk'
UNION ALL SELECT 'tbpo_jasa_number_counter','counter_type,period_key'
UNION ALL SELECT 'tbpo_jasa_purchase_submission','source_reference'
UNION ALL SELECT 'tbpo_jasa_purchase_submission','id_po_nk'
UNION ALL SELECT 'tbpo_jasa_purchase_receipt','idempotency_token'
UNION ALL SELECT 'tbpo_jasa_purchase_receipt','id_transnk'
UNION ALL SELECT 'tbpo_jasa_purchase_receipt','reversal_of_id'
UNION ALL SELECT 'tbpo_jasa_stock_receipt','idempotency_token'
UNION ALL SELECT 'tbpo_stock_lifo_batch_nk','id_transnk_masuk'
) r LEFT JOIN (
 SELECT table_name,GROUP_CONCAT(column_name ORDER BY seq_in_index SEPARATOR ',') cols
 FROM information_schema.statistics WHERE table_schema=DATABASE() AND non_unique=0 GROUP BY table_name,index_name
) i ON i.table_name=r.table_name AND i.cols=r.cols WHERE i.table_name IS NULL;

SELECT table_name,column_name,column_type AS insufficient_capacity FROM information_schema.columns WHERE table_schema=DATABASE() AND ((table_name='tbpo_jasa_biaya_aktual' AND column_name='verification_status' AND character_maximum_length<CHAR_LENGTH('OTOMATIS_TERVERIFIKASI')) OR (table_name='tbpo_jasa_request' AND column_name='status' AND character_maximum_length<40));

SELECT table_name,engine AS non_transactional_engine FROM information_schema.tables WHERE table_schema=DATABASE() AND (table_name LIKE 'tbpo_jasa_%' OR table_name IN ('tbpo_po_nk','tbpo_detail_po_nk','tbpo_transaksi','tbpo_stock_lifo_batch_nk','tbpo_stock_lifo_allocation')) AND engine<>'InnoDB';
